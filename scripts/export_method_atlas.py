"""Build the public research snapshot locally with the method library's UI environment.

Usage: <library>/.venv-ui/bin/python scripts/export_method_atlas.py <library> <output>
The destination must be empty. Review the generated snapshot before installing it.
"""
import argparse
import html
import importlib.util
import json
import re
from pathlib import Path

import yaml
from markdown_it import MarkdownIt

md = MarkdownIt("js-default", {"html": False, "linkify": False}).disable(["image", "autolink", "link"])
esc = html.escape
FIELDS = {
    "research_question": "研究问题", "thesis": "来源论点", "return_mechanism": "收益机制",
    "evidence": "证据", "causal_mechanism": "因果机制", "analytical_method": "方法提取",
    "assumptions": "假设", "valuation_logic": "估值逻辑", "counterarguments": "反面论据",
    "catalysts": "催化因素", "falsification": "推翻条件", "transferability": "可迁移性",
    "corrections": "更正",
}
LAYERS = {"source_fact": "来源陈述", "author_judgment": "来源作者判断",
          "ai_inference": "AI 推导", "own_extension": "研究延伸"}
PRIVATE = re.compile(r'(?i)(?:/Users/|/home/|file://|~/|[\w.+-]+@[\w.-]+\.[a-z]{2,}|github_pat_|gh[pousr]_[a-zA-Z0-9]{20,}|-----BEGIN .*PRIVATE KEY|(?:company-dossiers|research-private|research-method-extraction|legosmos)/|materials/)')
LINK = re.compile(r'!?\[([^\]\n]*)\]\(([^)\n]+)\)')


def clean(value):
    text = re.sub(r"<!--.*?-->", "", str(value), flags=re.S)
    text = LINK.sub(lambda m: m[1], text)
    text = text.replace("company-dossiers", "公司研究档案")
    text = re.sub(r"(?<![A-Za-z0-9])(?:[A-Za-z0-9*{},_-]+/)+[A-Za-z0-9*{},_-]+\.(?:md|ya?ml|py|json)\b",
                  lambda m: m[0].split("/")[-1].rsplit(".", 1)[0], text)
    return text.strip()


def render(text):
    # Only local links generated by this exporter become clickable.
    return md.render(clean(text))


def pick(data, fields):
    return {key: data[key] for key in fields.split() if key in data}


def document(title, body):
    return (f'<!doctype html><html lang="zh-CN"><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>{esc(title)} · 研究方法库</title><link rel="stylesheet" href="../app.css">'
            '<main class="public-results"><nav><a href="../../">OS 首页</a> · '
            '<a href="../">方法图谱</a> · <a href="./">全部成果</a></nav>'
            f'<h1>{esc(title)}</h1>{body}</main></html>')


def record_body(r):
    source = r["source"]
    body = [f'<p>{esc(clean(source["author"]))} · {esc(str(source.get("published_on") or "日期未定"))} · {esc(r["status"])}</p>',
            '<p>条目保留提取时的来源归属与核对状态。“已核对”表示与记录指定的材料版本对照过。</p>']
    for key, title in FIELDS.items():
        rows = r.get(key) or []
        if not rows:
            continue
        body.append(f'<h2>{title}</h2><ol>')
        for row in rows:
            verified = {True: "已核对", False: "未标为已核对"}.get(row.get("verified"), "未注明核对")
            where = clean(row.get("location", ""))
            label = LAYERS.get(row.get("layer"), row.get("layer", ""))
            body.append(f'<li>{esc(clean(row["text"]))}<br><small>{esc(label)} · {verified} {esc(where)}</small></li>')
        body.append('</ol>')
    if r.get("gaps"):
        body.append('<h2>方法缺口</h2><dl>')
        for g in r["gaps"]:
            body.append(f'<dt>{esc(g["id"])} · {esc(clean(g["question"]))}</dt><dd>{esc(clean(g["reach"]))} · {esc(g["status"])}</dd>')
            for part in g.get("resolved_parts") or []:
                body.append('<dd>' + ' · '.join(esc(clean(part[k])) for k in ('topic', 'answer', 'boundary', 'source') if k in part) + '</dd>')
        body.append('</dl>')
    return ''.join(body)


def build(library, out):
    spec = importlib.util.spec_from_file_location("method_library", library / "ui/build.py")
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    source = builder.build_data()
    out.mkdir(parents=True, exist_ok=True)
    if any(out.iterdir()):
        raise ValueError("Export to an empty directory")
    dest = out / "results"
    dest.mkdir()
    groups = {}

    def result(group, ident, title, body):
        if not re.fullmatch(r'[a-z0-9-]+', ident):
            raise ValueError(f"Invalid result id: {ident}")
        path = dest / (ident + ".html")
        if path.exists():
            raise ValueError(f"Duplicate result: {ident}")
        path.write_text(document(title, body))
        groups.setdefault(group, []).append((ident, title))

    data = pick(source, "assessment_basis built_at stages common routes relationship_count batch_counts records mechanisms")
    for mech in data["mechanisms"]:
        mech["missing_html"] = re.sub(r'<a\b[^>]*>(.*?)</a>', r'\1', mech["missing_html"], flags=re.S)
    data["cards"] = []
    reports = {p.stem: p for p in Path("notes/companies").glob("*/*/*.md")}
    for c in source["cards"]:
        card = pick(c, "id name_zh name_en question_summary kind status related stage mechanisms common source_mix")
        card["sections"] = {key: clean(v) for key, v in c["sections"].items()}
        card["section_html"] = {key: render(v) for key, v in card["sections"].items()}
        card["reports"] = [{"id": rid, "url": "../" + path.with_suffix("").as_posix() + "/"}
                           for rid, path in sorted(reports.items()) if any(rid in v for v in c["sections"].values())]
        card["question_summary"] = clean(card["question_summary"])
        card["sources"] = [{**pick(s, "type recorded"), "ref": clean(s["ref"])} for s in c["sources"]]
        card["evidence"] = [{**pick(e, "title ref depth status tier review"),
                             "source_path": f'results/{e["record"]}.html'} for e in c["evidence"]]
        m = c["ui"]
        card["ui"] = {**pick(m, "batch rationale assessment"),
                      "availability": pick(m["availability"], "status channels note"),
                      "scope": pick(m["scope"], "types note"),
                      "dependencies": pick(m["dependencies"], "methods requirements unresolved")}
        for run in m.get("executions", []):
            item = pick(run, "company steps review reached first_guess test")
            if run.get("technical_review"):
                item["technical_review"] = pick(run["technical_review"], "result by date")
            card["ui"].setdefault("executions", []).append(item)
        data["cards"].append(card)

    for entry in data["records"]:
        rid = entry["id"]
        r = yaml.safe_load((library / "records" / (rid + ".yaml")).read_text())
        links = [f'<li><a href="../#method={c["id"]}">{esc(c["name_zh"])}</a></li>'
                 for c in source["cards"] if any(e["record"] == rid for e in c["evidence"])]
        related = '<h2>关联方法</h2><ul>' + ''.join(links) + '</ul>' if links else ''
        result("材料研究成果", rid, entry["title"], record_body(r) + related)

    for path in sorted((library / "tests").glob("20*.md")):
        text = path.read_text()
        title = re.search(r'^# (.+)', text, re.M)[1]
        sections = builder.split_sections(text)
        body = ''.join(f'<h2>{esc(k)}</h2>{render(v)}' for k, v in sections.items()
                       if k in {"为什么测", "结果", "和预期对照", "两家对照", "发现的缺口与后续", "复核"})
        if not body:
            body = render(text.split('# ' + title, 1)[1])
        meta = yaml.safe_load(text.split("---", 2)[1])
        body = f'<p>{esc(str(meta["date"]))} · {esc(meta["status"])}</p>' + body
        result("查库与执行案例", path.stem, title, body)

    for folder, names in (("methods", ["by-industry", "by-task", "query-tests", "candidates",
                                       "probability-sizing-integration", "dependency-audit"]),
                          ("tests", ["gaps"]), ("templates", ["market-size-research"])):
        for ident in names:
            text = (library / folder / (ident + ".md")).read_text()
            title, body = text.split('\n', 1)
            result("研究路径与待解问题", ident, title.removeprefix("# "), render(body))
    result("研究路径与待解问题", "analysis-result", "公司研究结果的记录结构",
           "<ol>" + "".join("<li>" + esc(title) + "</li>" for title in re.findall(
               r"^## (.+)", (library / "templates/analysis-result.md").read_text(), re.M))
           + "</ol><p>分别记录研究范围、证据层级、可检验判断与复核结果。个人填写的实例保存在私有档案。</p>")
    body = []
    for group, entries in groups.items():
        body.append(f'<h2>{esc(group)} · {len(entries)}</h2><ul>')
        body.extend(f'<li><a href="{i}.html">{esc(t)}</a></li>' for i, t in entries)
        body.append('</ul>')
    body.append('<h2>全部方法卡</h2><ul>')
    body.extend(f'<li><a href="../#method={c["id"]}">{esc(c["name_zh"])}</a></li>' for c in data["cards"])
    (dest / "index.html").write_text(document("研究成果", ''.join(body) + '</ul>'))
    (out / "catalog.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    for path in out.rglob("*"):
        if path.is_file() and PRIVATE.search(path.read_text()):
            raise ValueError(f"Private reference in {path.name}")
    print(len(data["cards"]), "cards;", {k: len(v) for k, v in groups.items()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("library", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    build(args.library.resolve(), args.out)
