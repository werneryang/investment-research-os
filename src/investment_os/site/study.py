def chart_panel(run_href: str, available: list[str], wanted: tuple[tuple[str, str], ...],
                interactive: bool = True) -> str:
    """图表面板：静态图默认可见；交互图表加载并生成成功后才替换显示（渐进增强）。

    脚本或数据加载失败、浏览器禁用脚本时，读者仍能看到与完整报告相同的静态图。
    """
    figs = "".join(
        f'<a href="{run_href}/figures/{f}" target="_blank" rel="noopener" title="{L("查看大图", "Open full size")}">'
        f'<img loading="lazy" src="{run_href}/figures/{f}" alt="{e(alt)}"></a>'
        for f, alt in wanted if f in available)
    static = figs or f'<p class="muted small">{L("该运行没有静态图。", "This run has no static figures.")}</p>'
    if figs and is_en():
        static += '<p class="muted small">Static figures are labelled in Chinese; the interactive chart is in English.</p>'
    src = f' data-src="{run_href}/chart.json"' if interactive else ""
    return (f'<div class="chart-panel"{src}>'
            f'<div class="chart-static figs">{static}</div>'
            '<div class="interactive" hidden></div>'
            '<p class="chart-status small muted" role="status"></p></div>')


def localized_findings(item: dict[str, Any]) -> list[dict[str, Any]]:
    """当前语言的关键发现：中文为运行记录原文；英文由同一规则的英文措辞从结构化结果生成。"""
    if not is_en():
        return item["findings"]
    return english_findings(item["result"], item["findings"])


def findings_list(items: list[dict[str, Any]], limit: int | None = None) -> str:
    if not items:
        return f'<p class="muted">{L("该研究分支暂无规则化的关键发现。", "This research branch has no rule-based findings yet.")}</p>'
    rows = []
    for f in items[:limit] if limit else items:
        evidence = "".join(f"<li><code>{e(k)}</code> = {e(num(v, 2) if isinstance(v, float) else v)}</li>"
                           for k, v in f["evidence"].items())
        text = e(f["text"]) if f.get("translated", True) else f'<span lang="zh-CN">{e(f["text"])}</span>'
        rows.append(f'<li><span>{text}</span>'
                    f'<details class="basis"><summary>{L("依据", "Basis")}</summary><ul>{evidence}</ul></details></li>')
    return f'<ol class="findings">{"".join(rows)}</ol>'


def _method(result: dict[str, Any], renderer: Renderer) -> str:
    items = renderer.method_items(result) + [L(
        "<li>关键发现由固定规则在运行时生成并记录（规则版本、指纹与参数见「关键发现」下方）；只描述，不作预测或交易判断。</li>",
        "<li>Key findings are generated by fixed rules at run time and recorded (rule version, fingerprint and parameters "
        "appear under Key findings); they describe only, with no forecast or trading judgement.</li>")]
    return f'<ul class="method">{"".join(items)}</ul>'


def evidence_panel(item: dict[str, Any], registry: Registry, run_href: str) -> str:
    """证据面板：逐项列出证据，不汇总成一个可信度分数。"""
    m, r, ver = item["manifest"], item["result"], item["verification"]
    val = r["validation"]
    renderer = get_renderer(r["branch"])
    rows = [(L("研究用途", "Use"), f"{e(RESULT_TYPE_LABEL.get(r['result_type'], r['result_type']))} · "
                                  f"{e(USE_LABEL[use_key(r)])}{L('；', '; ')}{e(renderer.use_note)}")]
    for inp in m.get("inputs", []):
        role = L("输入 · ", "Input · ") + e(inp["role"])
        if not inp.get("used", True):
            rows.append((role, f'<span class="muted">{L("未使用：", "Not used: ")}{te(inp.get("reason", ""))}</span>'))
            continue
        spec = registry.datasets.get(inp["dataset_id"])
        source = registry.sources[spec.source_id].publisher if spec else inp["dataset_id"]
        rows.append((role,
                     f"{te(source)} · <code>{e(inp['dataset_id'])}</code> {L('版本', 'version')} <code>{e(inp['version_id'])}</code>"
                     f"{L('（内容校验值 ', ' (content hash ')}<code>{e(inp['content_hash'][:12])}</code>{L('）· 核验状态：', ') · verification: ')}"
                     f"{e(VERIFY_LABEL.get(inp['source_status'], inp['source_status']))}"
                     + (f"<div>{use_scope_chip(inp.get('use_scope'))}</div>" if inp.get("use_scope") else "")))
    rows += renderer.evidence_rows(r)
    integrity = item.get("artifact_integrity")
    if integrity:
        rows.append((L("保存产物完整性", "Saved artifact integrity"),
                     chip(integrity["status"], CHECK_LABEL[integrity["status"]]) + " "
                     + L(f"本次构建核对 {integrity['checked_files']} 个输出文件及保存结果的内容校验值。",
                         f"This build checked {integrity['checked_files']} output files and the saved result hash.")))
    spot = val.get("raw_spot_check")
    if spot:
        n, bad = spot.get("checked", 0), len(spot.get("failures", []))
        rows.append((L("原始快照抽查", "Raw snapshot spot check"),
                     f"{chip(spot.get('status'), CHECK_LABEL.get(spot.get('status'), ''))} "
                     + L(f"抽查 {n} 个观测，不一致 {bad} 个。", f"{n} observations checked, {bad} mismatched. ")
                     + f"<span class='muted small'>{e(CHECK_NOTES['raw_spot_check'])}</span>"))
    cross = val.get("cross_check")
    if cross:
        detail = (L(f"共同日期 {cross['matched']} 天，最大差 {num(cross.get('max_abs_diff'), 4)}",
                    f"{cross['matched']} common dates, max difference {num(cross.get('max_abs_diff'), 4)}")
                  if cross.get("matched") else te(cross.get("reason", "")))
        rows.append((L("同源一致性检查", "Same-source consistency check"),
                     f"{chip(cross.get('status'), CHECK_LABEL.get(cross.get('status'), ''))} "
                     f"{detail}{L('。', '. ')}<span class='muted small'>{e(CHECK_NOTES['cross_check'])}</span>"))
    recompute = L("固定输入重算", "Pinned-input recomputation")
    if ver:
        excluded = ver.get("excluded_roles", [])
        if ver.get("scope") == "partial":
            scope = L("部分（未重算 " + "、".join(excluded) + "）", "partial (not recomputed: " + ", ".join(excluded) + ")")
        else:
            scope = L("完整", "full")
        ok = ver["reproduced"]
        rows.append((recompute, f"{chip('pass' if ok else 'fail', L('一致', 'Matches') if ok else L('不一致', 'Differs'))} "
                                f"{L('范围：', 'Scope: ')}{e(scope)}{L('；结果校验值 ', '; result hash ')}"
                                f"<code>{e((m.get('result_hash') or '')[:16])}</code>{L('。', '. ')}"
                                f"<span class='muted small'>{e(CHECK_NOTES['reproduce'])}</span>"))
    else:
        rows.append((recompute, f'<span class="muted">{L("未执行", "Not run")}</span>'))
    code = m.get("code", {})
    rows.append((L("代码版本", "Code version"), f"<code>{e((code.get('git_commit') or '—')[:12])}</code>"
                 f"{L('（含未提交改动）', ' (with uncommitted changes)') if code.get('dirty') else ''}"))
    unsupported = r.get("unsupported", [])
    rows.append((L("不支持的结论", "Unsupported conclusions"), L("无", "None") if not unsupported else
                 "<ul>" + "".join(f"<li>{te(u['item'])}{L('：', ': ')}{te(u['reason'])}</li>" for u in unsupported)
                 + "</ul>"))
    table = "".join(f"<tr><th scope='row'>{k}</th><td>{v}</td></tr>" for k, v in rows)
    limits = "".join(f"<li>{te(x)}</li>" for x in r.get("limitations", []))
    return f"""
<div class="evidence"><table>{table}</table></div>
<h3 class="sub">{L("限制", "Limitations")}</h3><ul class="limits-list">{limits}</ul>
<p class="small muted">{L("原始记录：", "Raw records: ")}<a href="{run_href}/manifest.json">{L("运行清单", "run manifest")}</a> ·
<a href="{run_href}/result.json">{L("结构化结果", "structured result")}</a> ·
<a href="{run_href}/report.html">{L("完整报告", "full report (Chinese)")}</a></p>"""


def interpretation_note(interp: dict[str, Any] | None, branch: str) -> str:
    """发现的来源：运行时记录，还是事后用当前规则生成。"""
    if not interp:
        return ""
    params = get_renderer(branch).rule_params_label(interp.get("params", {}))
    fp = (interp.get("rule_fingerprint") or "—")[:8]
    rule = L(f"{interp['rule_version']}（指纹 {fp}" + (f"，{params}" if params else "") + "）",
             f"{interp['rule_version']} (fingerprint {fp}" + (f", {params}" if params else "") + ")")
    translated = (" The run recorded these findings in Chinese; this page shows English wording generated by the "
                  "same rule from the same structured result." if is_en() else "")
    if interp["origin"] == "retrospective":
        return ('<p class="small warn">' + L(f"以下发现由当前规则 {e(rule)} 在发布网站时事后生成；"
                                             "该运行当时没有记录发现，措辞可能与当时的规则不同。",
                                             f"These findings were generated retrospectively by the current rule "
                                             f"{e(rule)} when the site was published; the run did not record findings "
                                             "at the time, so the wording may differ from the rule then.")
                + f"{translated}</p>")
    note = '<p class="small muted">' + L(f"以下发现在运行时按规则 {e(rule)} 生成并记录，纳入复现校验。",
                                         f"These findings were generated at run time by rule {e(rule)}, recorded, "
                                         "and covered by reproduction checks.")
    if interp.get("rules_changed"):
        note += L("当前规则已变化；这里显示的是运行当时的发现，不按新规则改写。",
                  " The rule has changed since; the findings shown are those from the run, not rewritten by the new rule.")
    return note + translated + "</p>"


def _state_change(d: dict[str, str]) -> str:
    """一条定性状态变化；状态以中文记录，英文页面逐词对照显示。"""
    if not is_en():
        return e(f"{d['item']}：{d['from']} → {d['to']}")
    return e(f"{state_text(d['item'])}: {state_text(d['from'])} → {state_text(d['to'])}")


def _history(study_id: str, runs: list[dict[str, Any]], archived: dict[str, Any] | None,
             repo: str | None, up: str, renderer: Renderer) -> str:
    timeline = []
    chronological = list(reversed(runs))
    for prev, cur in zip(chronological, chronological[1:]):  # noqa: B905 - 相邻两次运行
        diffs = state_changes((prev.get("interpretation") or {}).get("state", {}),
                              (cur.get("interpretation") or {}).get("state", {}))
        if diffs:
            timeline.append({"item": cur, "diffs": diffs, "between": run_differences(prev, cur)})
    if timeline:
        change_rows = "".join(
            f"<tr><td class=\"nowrap\">{e(t['item']['result']['data_cutoff'])}</td>"
            f"<td>{'<br>'.join(_state_change(d) for d in t['diffs'])}</td>"
            f"<td class='small'>{'<br>'.join(e(x) for x in t['between']) or '—'}</td>"
            f"<td><a class=\"nowrap\" href=\"{up}runs/{e(t['item']['manifest']['run_id'])}/report.html\">{L('报告', 'Report')}</a></td></tr>"
            for t in reversed(timeline))
        change_html = (f'<p class="small muted">{L("「两次运行之间的差异」只列出可以客观比较的项目（研究窗口、数据版本、代码、解释规则），不推断变化的原因；滚动窗口移动、数据修订、方法或规则修改都可能带来结论变化。", "“Differences between runs” lists only what can be compared objectively (study window, data versions, code, interpretation rules) and does not infer causes; a moving window, data revisions, or method or rule changes can all change conclusions.")}</p>'
                       f'<div class="scroll"><table><thead><tr><th>{L("数据截止", "Data cutoff")}</th>'
                       f'<th>{L("结论变化", "Change in conclusions")}</th>'
                       f'<th>{L("两次运行之间的差异", "Differences between runs")}</th><th></th></tr></thead>'
                       f'<tbody>{change_rows}</tbody></table></div>')
    else:
        # 列出的运行可能含本次发布、未单独归档的最新运行，归档数分开计
        n_arch = sum(r["manifest"]["run_id"] in archived for r in runs) if archived is not None else None
        listed = L(f"在列出的 {len(runs)} 次运行中", f"Across the {len(runs)} listed runs")
        if n_arch is not None:
            listed += L(f"（其中已归档 {n_arch} 次）", f" ({n_arch} archived)")
        change_html = '<p class="muted">' + L(f"{listed}，定性状态（{e(renderer.state_description)}）没有变化。",
                                              f"{listed}, the qualitative state ({e(renderer.state_description)}) "
                                              "did not change.") + "</p>"
    rows = []
    for item in runs:
        m, r = item["manifest"], item["result"]
        note = ""
        if archived is not None:
            note = (tx(archived[m["run_id"]]["reason"]) if m["run_id"] in archived
                    else L("本次发布的最新运行（结论与上一归档相同，未单独归档）",
                           "Latest run in this release (same conclusions as the last archived run, not archived "
                           "separately)"))
        ver = item["verification"]
        rows.append(
            f"<tr><td class=\"nowrap\">{e(m['started_at'][:16].replace('T', ' '))}</td>"
            f"<td class=\"nowrap\">{e(r['data_cutoff'])}</td>"
            f"<td>{chip(m['status'], STATUS_LABEL.get(m['status'], m['status']))}</td>"
            + "".join(f"<td>{e(fn(r))}</td>" for _, fn in renderer.history_columns) +
            f"<td>{L('一致', 'Matches') if ver and ver['reproduced'] else (L('不一致', 'Differs') if ver else '—')}"
            f"{L('（部分）', ' (partial)') if ver and ver.get('scope') == 'partial' else ''}</td>"
            f"<td><a class=\"nowrap\" href=\"{up}runs/{e(m['run_id'])}/report.html\">{L('报告', 'Report')}</a>"
            f"<div class='small muted'>{e(note)}</div></td></tr>")
    archive_link = (f' <a href="{e(repo)}/tree/archive">{L("运行档案（archive 分支）", "Run archive (archive branch)")}</a>'
                    if repo else "")
    columns = "".join(f"<th>{e(label)}</th>" for label, _ in renderer.history_columns)
    head = L("<th>运行时间（UTC）</th><th>数据截止</th><th>状态</th>", "<th>Run time (UTC)</th><th>Data cutoff</th><th>Status</th>")
    tail = L("<th>固定输入重算</th><th>报告</th>", "<th>Pinned-input recomputation</th><th>Report</th>")
    note = L("""只有实质结论（结果、覆盖、限制、核验结论）变化时才归档新运行，报告地址长期有效。
日后复现：<code>iros archive restore &lt;档案&gt; --with-data</code> 后 <code>iros verify &lt;run_id&gt;</code>；
未归档数据的可选输入（FRED 交叉核验）不重算，标为部分复现。""",
             """A new run is archived only when its substantive conclusions (results, coverage, limitations,
verification) change; report addresses stay valid. To reproduce later: <code>iros archive restore &lt;archive&gt;
--with-data</code>, then <code>iros verify &lt;run_id&gt;</code>. Optional inputs whose data is not archived (the
FRED cross-check) are not recomputed and are marked as partial reproduction. Full reports are in Chinese.""")
    return f"""
<h3 class="sub">{L("发现变化记录", "Changes in findings")}</h3>{change_html}
<h3 class="sub">{L("历次运行", "All runs")}</h3>
<div class="scroll"><table><thead><tr>{head}{columns}
{tail}</tr></thead><tbody>{''.join(rows)}</tbody></table></div>
<p class="small muted">{note}{archive_link}</p>"""


def study_page(study_id: str, runs: list[dict[str, Any]], archived: dict[str, Any] | None,
               registry: Registry, content: dict[str, Any], build: dict[str, Any], references: str = "") -> str:
    latest = runs[0]
    m, r = latest["manifest"], latest["result"]
    up = root(2)
    run_href = f"{up}runs/{m['run_id']}"
    meta = content.get("studies", {}).get(study_id, {})
    renderer = get_renderer(r["branch"])
    target = {"rates_curve": "curve", "curve_attribution": "attribution", "par_bond_scenarios": "bond-scenarios"}.get(r["branch"])
    stats = renderer.key_stats(r)
    if target:
        stats = f'<div id="{target}">{stats}</div>'
    period = L(f"研究期间 {e(r['scope'].get('start'))} 至 {e(r['scope'].get('end'))} · 数据截止 {e(r['data_cutoff'])}",
               f"Study period {e(r['scope'].get('start'))} to {e(r['scope'].get('end'))} · data cutoff {e(r['data_cutoff'])}")
    body = f"""
<header class="top"><div class="wrap">
  <p class="eyebrow">{te(meta.get('label', L('研究', 'Study')))} · {e(RESULT_TYPE_LABEL.get(r['result_type'], ''))}</p>
  <h1>{te(r['title'])}</h1>
  <p class="meta">{period}
  · {chip(m['status'], L('本次运行 · ', 'This run · ') + STATUS_LABEL.get(m['status'], m['status']))}</p>
</div></header>
<main class="wrap">
<section id="question"><h2>{L("研究问题", "Research question")}</h2><p class="lead">{te(r['question'])}</p></section>
<section id="findings"><h2>{L("关键发现", "Key findings")}</h2>{findings_list(localized_findings(latest))}{interpretation_note(latest.get('interpretation'), r['branch'])}{stats}</section>
<section id="visuals"><h2>{L("可视化证据", "Visual evidence")}</h2>
  {"" if renderer.inline_visuals else chart_panel(run_href, latest.get("figures", []), renderer.figures, renderer.chart_data(r) is not None)}
  <h3 class="sub">{e(renderer.coverage_title)}</h3>{renderer.coverage_section(r)}
</section>
{references}
<section id="method"><h2>{L("方法", "Method")}</h2>{_method(r, renderer)}</section>
<section id="evidence"><h2>{L("证据与限制", "Evidence and limitations")}</h2>
  <div class="checks">{check_chips(r, latest['verification'])}</div>
  {evidence_panel(latest, registry, run_href)}</section>
<section id="history"><h2>{L("历史与复现", "History and reproduction")}</h2>{_history(study_id, runs, archived, build.get('repo_url'), up, renderer)}</section>
</main>"""
    return shell(f"{tx(r['title'])} · Investment Research OS", body, build, page=f"studies/{study_id}/", charts=True,
                 description=tx(r["question"]))


def redirect(target: str) -> str:
    return (f'<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url={e(target)}">'
            f'<link rel="canonical" href="{e(target)}"><p>已移至 <a href="{e(target)}">{e(target)}</a></p>')
